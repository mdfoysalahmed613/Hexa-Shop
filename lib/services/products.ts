/**
 * Get all products with category info, images, and variants
 */
export async function getProducts(): Promise<GetProductsResult> {
  try {
    const supabase = await createClient();

    const { data, error } = await supabase
      .from("products")
      .select(
        `
        *,
        category_data:categories!category_id(id, name, slug),
        images:product_images(id, image_url, is_primary),
        variants:product_variants(id, price, compare_price, stock, is_active, sku, size, color)
      `
      )
      .order("created_at", { ascending: false });

    if (error) {
      console.error("Fetch error:", error);
      return { ok: false, error: "Failed to fetch products", data: [] };
    }

    // Transform data
    const products = (data || []).map((product) => {
      const images = (product.images || []).map(
        (img: { id: string; image_url: string; is_primary: boolean }) => ({
          ...img,
          url: img.image_url, // Map image_url to url for backwards compatibility
        })
      );
      const primaryImage =
        images.find((img: ProductImage) => img.is_primary) || images[0];

      // Derive is_active from variants - product is active if any variant is active
      const variants = product.variants || [];
      const is_active = variants.some(
        (v: { is_active: boolean }) => v.is_active
      );

      return {
        ...product,
        is_active,
        category: product.category_id, // Alias for backwards compatibility
        category_name: product.category_data?.name || product.category_id,
        primary_image: primaryImage,
        images,
      };
    });

    return { ok: true, data: products };
  } catch (e) {
    const message = e instanceof Error ? e.message : "Unknown error";
    console.error("Get products error:", e);
    return { ok: false, error: message, data: [] };
  }
}

