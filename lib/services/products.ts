"use server";

/**
 * Products Service
 *
 * Server Actions for product CRUD operations.
 * Products support variants (price, stock) and multiple images.
 *
 * Functions:
 * - getProducts() - List all products with relations
 * - getProduct(id) - Get single product by ID
 * - getProductBySlug(slug) - Get product by URL slug
 * - getProductsByCategory(categoryId) - Filter by category
 * - searchProducts(query) - Full-text search
 * - addProduct(formData) - Create product with variants/images
 * - updateProduct(id, formData) - Update product
 * - deleteProduct(id) - Delete product (admin only)
 * - toggleProductStatus(id) - Toggle active/inactive
 *
 * Storage: Images stored in 'product-images' bucket (2MB limit)
 */

import { createClient } from "@/lib/supabase/server";
import { revalidatePath } from "next/cache";
import { hasAdminAccess, isAdmin } from "@/lib/auth/roles";

// ============================================================================
// Types
// ============================================================================

export interface Product {
  id: string;
  name: string;
  slug: string;
  description: string | null;
  category_id: string;
  category: string; // Alias for backwards compatibility
  category_name?: string;
  is_active: boolean;
  created_at: string;
  // Relations
  images?: ProductImage[];
  primary_image?: ProductImage;
  variants?: ProductVariant[];
  category_data?: {
    id: string;
    name: string;
    slug: string;
    has_variants?: boolean;
  };
}

export interface ProductImage {
  id: string;
  product_id: string;
  url: string;
  image_url?: string;
  is_primary: boolean;
  display_order: number;
}

export interface ProductVariant {
  id: string;
  product_id: string;
  price: number;
  compare_price: number | null;
  stock: number;
  is_active: boolean;
  sku?: string | null;
  size?: string | null; // S, M, L, XL, XXL
  color?: string | null;
}

// Form data types for variants
interface VariantFormInput {
  id?: string;
  price: number;
  compare_price?: number | null;
  stock: number;
  is_active: boolean;
  sku?: string | null;
  size?: string | null;
  color?: string | null;
}

interface ActionResult {
  ok: boolean;
  error?: string;
}

interface AddProductResult extends ActionResult {
  productId?: string;
}

interface GetProductsResult extends ActionResult {
  data?: Product[];
}

interface GetProductResult extends ActionResult {
  data?: Product;
}

