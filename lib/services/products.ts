/**
 * Get all products with category info and images
 */
export async function getProducts(): Promise<GetProductsResult> {
  try {
    const supabase = await createClient();

    const { data, error } = await supabase
      .from("products")
      .select(
        `
        *,
        category_data:categories!category(id, name, slug),
        images:product_images(id, url, is_primary, display_order)
      `
      )
      .order("created_at", { ascending: false });

    if (error) {
      console.error("Fetch error:", error);
      return { ok: false, error: "Failed to fetch products", data: [] };
    }

    // Transform data
    const products = (data || []).map((product) => {
      const images = product.images || [];
      const primaryImage =
        images.find((img: ProductImage) => img.is_primary) || images[0];

      return {
        ...product,
        category_name: product.category_data?.name || product.category,
        primary_image: primaryImage,
        images: images.sort(
          (a: ProductImage, b: ProductImage) =>
            a.display_order - b.display_order
        ),
      };
    });

    return { ok: true, data: products };
  } catch (e) {
    const message = e instanceof Error ? e.message : "Unknown error";
    console.error("Get products error:", e);
    return { ok: false, error: message, data: [] };
  }
}

/**
 * Get a single product by ID with full details
 */
